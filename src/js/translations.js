// Função para obter tradução com suporte a parâmetros
// Exemplo: t('admin.bannedForDays', 'pt-BR', {n: 5}) → "Usuário banido por 5 dias."
export function t(key, language = 'pt-BR', params = {}) {
  let text = translations[language]?.[key] || translations['pt-BR'][key] || key;
  
  // Substituir parâmetros no formato {param}
  Object.keys(params).forEach(param => {
    const regex = new RegExp(`\\{${param}\\}`, 'g');
    text = text.replace(regex, params[param]);
  });
  
  return text;
}
